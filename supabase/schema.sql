create table if not exists public.users (
    username text primary key,
    display_name text not null,
    salt text not null,
    password_hash text not null
);

create table if not exists public.sessions (
    token_hash text primary key,
    username text not null references public.users(username) on delete cascade,
    expires_at bigint not null
);

create table if not exists public.conversations (
    id text primary key,
    kind text not null check (kind in ('dm', 'group')),
    name text,
    created_by text not null references public.users(username),
    created_at bigint not null
);

create table if not exists public.conversation_members (
    conversation_id text not null references public.conversations(id) on delete cascade,
    username text not null references public.users(username) on delete cascade,
    primary key (conversation_id, username)
);

create table if not exists public.messages (
    id bigint generated by default as identity primary key,
    conversation_id text not null references public.conversations(id) on delete cascade,
    username text not null references public.users(username),
    body text not null,
    created_at bigint not null
);

create table if not exists public.attachments (
    id bigint generated by default as identity primary key,
    message_id bigint not null unique references public.messages(id) on delete cascade,
    name text not null,
    size bigint not null,
    storage_path text not null unique
);

create index if not exists sessions_expiration_idx
    on public.sessions (expires_at);
create index if not exists members_username_idx
    on public.conversation_members (username);
create index if not exists messages_conversation_id_idx
    on public.messages (conversation_id, id desc);

alter table public.users enable row level security;
alter table public.sessions enable row level security;
alter table public.conversations enable row level security;
alter table public.conversation_members enable row level security;
alter table public.messages enable row level security;
alter table public.attachments enable row level security;

grant usage on schema public to service_role;
grant all privileges on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to service_role;
alter default privileges in schema public
    grant all privileges on tables to service_role;
alter default privileges in schema public
    grant usage, select on sequences to service_role;

